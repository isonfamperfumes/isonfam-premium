/* ==========================================
   RENDER COLLECTION
========================================== */


function renderCollection() {

    const container =
        document.getElementById("scent-container");


    if (!container) {
        return;
    }


    const collection =
        document.body.dataset.collection;


    const products =
        Object.values(scents)
        .filter(
            scent =>
                scent.collection === collection
        );


    products.forEach(
        (scent, index) => {


            const section =
                document.createElement("section");


            section.className =
                "scent-section";


            section.innerHTML = `

                <div class="scent-image">

                    <img
                        src="${scent.image}"
                        alt="${scent.code}"
                        onerror="this.style.display='none'"
                    >

                    <span class="image-placeholder">
                        ${scent.code}
                    </span>

                </div>


                <div class="scent-details">

                    <p class="scent-number">
                        ${String(index + 1).padStart(2, "0")}
                    </p>


                    <p class="eyebrow dark">
                        ${collection === "dubai"
                            ? "DUBAI SCENTS"
                            : "PREMIUM SCENTS"}
                    </p>


                    <h2>
                        ${scent.code}
                    </h2>


                    <p class="scent-description">
                        ${scent.description}
                    </p>


                    <div class="scent-info">

                        <div>

                            <span>
                                FRAGRANCE PROFILE
                            </span>

                            <p>
                                ${scent.fragranceFamily}
                            </p>

                        </div>


                        <div>

                            <span>
                                TOP NOTES
                            </span>

                            <p>
                                ${scent.topNotes}
                            </p>

                        </div>


                        <div>

                            <span>
                                HEART NOTES
                            </span>

                            <p>
                                ${scent.heartNotes}
                            </p>

                        </div>


                        <div>

                            <span>
                                BASE NOTES
                            </span>

                            <p>
                                ${scent.baseNotes}
                            </p>

                        </div>


                        <div>

                            <span>
                                BEST FOR
                            </span>

                            <p>
                                ${scent.bestFor}
                            </p>

                        </div>

                    </div>


                    <div class="inspiration">

                        <span>
                            THE INSPIRATION
                        </span>

                        <p>
                            ${scent.inspiration}
                        </p>

                    </div>

                </div>

            `;


            container.appendChild(section);

        }
    );

}


/* ==========================================
   START
========================================== */

document.addEventListener(
    "DOMContentLoaded",
    renderCollection
);
